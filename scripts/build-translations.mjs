// Builds the KJV (1769) and Douay-Rheims (Challoner) text from scrollmapper/bible_databases (MIT-licensed
// packaging of public-domain texts). Writes compact per-book JSON and src/data/translations-meta.ts.
import { mkdirSync, writeFileSync } from 'node:fs';

const BASE = 'https://raw.githubusercontent.com/scrollmapper/bible_databases/master/formats/json/';
const WEB_ORDER = [
  'genesis','exodus','leviticus','numbers','deuteronomy','joshua','judges','ruth','1samuel','2samuel','1kings','2kings',
  '1chronicles','2chronicles','ezra','nehemiah','esther','job','psalms','proverbs','ecclesiastes','songofsolomon','isaiah',
  'jeremiah','lamentations','ezekiel','daniel','hosea','joel','amos','obadiah','jonah','micah','nahum','habakkuk','zephaniah',
  'haggai','zechariah','malachi','matthew','mark','luke','john','acts','romans','1corinthians','2corinthians','galatians',
  'ephesians','philippians','colossians','1thessalonians','2thessalonians','1timothy','2timothy','titus','philemon','hebrews',
  'james','1peter','2peter','1john','2john','3john','jude','revelation',
];
const NAMES = {
  '1samuel': '1 Samuel', '2samuel': '2 Samuel', '1kings': '1 Kings', '2kings': '2 Kings', '1chronicles': '1 Chronicles',
  '2chronicles': '2 Chronicles', songofsolomon: 'Song of Solomon', '1corinthians': '1 Corinthians', '2corinthians': '2 Corinthians',
  '1thessalonians': '1 Thessalonians', '2thessalonians': '2 Thessalonians', '1timothy': '1 Timothy', '2timothy': '2 Timothy',
  '1peter': '1 Peter', '2peter': '2 Peter', '1john': '1 John', '2john': '2 John', '3john': '3 John',
  '1maccabees': '1 Maccabees', '2maccabees': '2 Maccabees',
};
const title = (id) => NAMES[id] ?? id[0].toUpperCase() + id.slice(1);

// scrollmapper book name -> our id ("I Samuel" -> "1samuel", "Revelation of John" -> "revelation")
const idFor = (name) => {
  let n = name.replace(/^III /, '3').replace(/^II /, '2').replace(/^I /, '1').replace(/ of John$/, '');
  return n.toLowerCase().replace(/\s+/g, '');
};

const clean = (t) => t.replace(/[\[\]]/g, '').replace(/\s+/g, ' ').trim();

async function build(code, folder, limit) {
  const data = await (await fetch(`${BASE}${code}.json`)).json();
  mkdirSync(`src/data/${folder}`, { recursive: true });
  const books = [];
  for (const b of data.books.slice(0, limit)) {
    const id = idFor(b.name);
    const chapters = b.chapters.map((c) => c.verses.map((v) => '¶' + clean(v.text)));
    writeFileSync(`src/data/${folder}/${id}.json`, JSON.stringify(chapters));
    const words = chapters.map((ch) => ch.join(' ').replace(/¶/g, ' ').split(/\s+/).filter(Boolean).length);
    books.push({ id, name: title(id), words });
  }
  // Testament: everything before Matthew is Old Testament (includes the deuterocanon in the Catholic canon).
  const mat = books.findIndex((b) => b.id === 'matthew');
  const withT = books.map((b, i) => ({ ...b, testament: i < mat ? 'ot' : 'nt' }));
  const index = `// Generated by scripts/build-translations.mjs. Do not edit.\nexport const LOADERS: Record<string, () => string[][]> = {\n${books.map((b) => `  '${b.id}': () => require('./${b.id}.json'),`).join('\n')}\n};\n`;
  writeFileSync(`src/data/${folder}/index.ts`, index);
  console.log(code, books.length, 'books', withT.reduce((n, b) => n + b.words.length, 0), 'chapters');
  return withT;
}

const kjv = await build('KJV', 'kjv', 66);
const drc = await build('DRC', 'drc', 73);
// Sanity: KJV should be in the same order as WEB.
if (kjv.map((b) => b.id).join() !== WEB_ORDER.join()) throw new Error('KJV book order differs from WEB');

writeFileSync(
  'src/data/translations-meta.ts',
  `// Generated by scripts/build-translations.mjs. Do not edit.\nimport type { BookMeta } from './books';\nexport const KJV_BOOKS: BookMeta[] = ${JSON.stringify(kjv)};\nexport const DRC_BOOKS: BookMeta[] = ${JSON.stringify(drc)};\n`,
);
